import pcbnew

PREFIX = "PCBPILOT_JSON:"
NM_PER_MIL = 25400.0
CLASS_PREFIX = "PP"
DRU_BEGIN = "# pcbpilot:begin (generated by pcbpilot kicad netclasses; do not edit inside this block)"
DRU_END = "# pcbpilot:end"


def emit(obj, code=0):
    sys.stdout.write("\n" + PREFIX + json.dumps(obj, separators=(",", ":")) + "\n")
    sys.stdout.flush()
    sys.exit(code)


def mil(v):
    return round(v / NM_PER_MIL, 4)


def xy(p):
    return mil(p.x), mil(-p.y)


INNER = {}


def layer_id(board, layer):
    """pcbpilot copper layer id of a KiCad layer (0 = not copper)."""
    if layer == pcbnew.F_Cu:
        return 1
    if layer == pcbnew.B_Cu:
        return 2
    if not INNER:
        for k in range(1, 31):
            v = getattr(pcbnew, "In%d_Cu" % k, None)
            if v is not None:
                INNER[v] = 14 + k
    return INNER.get(layer, 0)


def kicad_layer_name(layer):
    try:
        return pcbnew.LayerName(layer)
    except Exception:
        return str(layer)


def chain_points(chain):
    pts = []
    for i in range(chain.PointCount()):
        p = chain.CPoint(i)
        pts.append([mil(p.x), mil(-p.y)])
    return pts


def source_of(points):
    """EasyEDA-style polygon source [x, y, "L", x, y, ...] (mil, y-up)."""
    if not points:
        return []
    out = [points[0][0], points[0][1], "L"]
    for p in points[1:]:
        out += [p[0], p[1]]
    return out


def bbox_of(points):
    xs = [p[0] for p in points]
    ys = [p[1] for p in points]
    return {"minX": min(xs), "minY": min(ys), "maxX": max(xs), "maxY": max(ys)}


def box_mil(box):
    # KiCad BOX2I (y-down) → y-up mil bbox.
    x0, y0 = box.GetX(), box.GetY()
    x1, y1 = x0 + box.GetWidth(), y0 + box.GetHeight()
    return {"minX": mil(x0), "minY": mil(-y1), "maxX": mil(x1), "maxY": mil(-y0)}


def poly_set_fills(ps):
    """One fill per outline: [outline contour, hole contours...] (even-odd)."""
    fills = []
    for i in range(ps.OutlineCount()):
        contours = [source_of(chain_points(ps.Outline(i)))]
        for j in range(ps.HoleCount(i)):
            contours.append(source_of(chain_points(ps.Hole(i, j))))
        fills.append({"source": contours})
    return fills


def lcsc_of(fp):
    want = {"lcsc", "lcsc part", "lcsc part #", "jlcpcb part #", "jlcpcb part", "lcsc#"}
    for f in fp.GetFields():
        if f.GetName().strip().lower() in want and f.GetText().strip():
            return f.GetText().strip()
    return ""


PAD_KIND = {}


def local_clearance(item):
    """A pad's or footprint's clearance override (mil), None when unset:
    KiCad 9+ returns an optional (None), older versions 0 for "none"."""
    try:
        v = item.GetLocalClearance()
    except Exception:
        return None
    if v is None:
        return None
    try:
        v = int(v)
    except (TypeError, ValueError):
        return None
    return mil(v) if v > 0 else None


def net_tie_groups(fp):
    """A net-tie footprint's pad groups ([["1", "2"], ...]): pads in one
    group may short different nets on purpose. [] when none. (The SWIG
    binding returns GetNetTiePadGroups as an opaque vector; GetNetTiePads
    gives each pad's group as a tuple.)"""
    try:
        if not fp.IsNetTie():
            return []
        fp.BuildNetTieCache()
        seen, out = set(), []
        for p in fp.Pads():
            g = sorted({q.GetNumber() for q in fp.GetNetTiePads(p)} | {p.GetNumber()})
            if len(g) > 1 and tuple(g) not in seen:
                seen.add(tuple(g))
                out.append(g)
        return out
    except Exception:
        return []


def pad_kind(shape):
    if not PAD_KIND:
        PAD_KIND.update({
            pcbnew.PAD_SHAPE_RECT: "RECT",
            pcbnew.PAD_SHAPE_ROUNDRECT: "RECT",
            pcbnew.PAD_SHAPE_CHAMFERED_RECT: "RECT",
            pcbnew.PAD_SHAPE_TRAPEZOID: "RECT",
            pcbnew.PAD_SHAPE_CIRCLE: "ELLIPSE",
            pcbnew.PAD_SHAPE_OVAL: "OVAL",
            pcbnew.PAD_SHAPE_CUSTOM: "POLYGON",
        })
    return PAD_KIND.get(shape, "POLYGON")


# Placeholder designators: a footprint never annotated ("REF**", KiCad's
# library default) or a logo/graphic ("G***"); "R?" is an unannotated part.
PLACEHOLDER_REF = re.compile(r"^[A-Za-z_]*[*?]+$")


def is_placeholder(ref):
    return not ref or bool(PLACEHOLDER_REF.match(ref))


def footprint_index(board):
    """One entry per footprint, in board order: {fp, key, ref, uuid}. The key
    is unique on the board: the footprint uuid; "ref:<designator>" when the
    board repeats the uuid (converted boards do: 203 footprints on 39 uuids
    seen) and the designator is unique; else "fp:<uuid>:<n>" (n-th footprint
    with that uuid in file order, stable for an unchanged file). Footprints
    are never keyed by designator alone: several "REF**" logos or two "H1"
    holes would overwrite each other."""
    fps = list(board.GetFootprints())
    by_uuid, by_ref = {}, {}
    for fp in fps:
        u, r = fp.m_Uuid.AsString(), fp.GetReference()
        by_uuid[u] = by_uuid.get(u, 0) + 1
        by_ref[r] = by_ref.get(r, 0) + 1
    entries, nth = [], {}
    for fp in fps:
        u, r = fp.m_Uuid.AsString(), fp.GetReference()
        if by_uuid[u] == 1:
            key = u
        elif by_ref[r] == 1:
            key = "ref:" + r
        else:
            nth[u] = nth.get(u, 0) + 1
            key = "fp:%s:%d" % (u, nth[u])
        entries.append({"fp": fp, "key": key, "ref": r, "uuid": u})
    return entries


def comp_keys(board):
    """(entries, footprints sharing a uuid with an earlier one)."""
    entries = footprint_index(board)
    seen = {}
    for e in entries:
        seen[e["uuid"]] = seen.get(e["uuid"], 0) + 1
    return entries, sum(n - 1 for n in seen.values())


def duplicate_refs(entries):
    """{designator: [entries]} for every designator on 2+ footprints."""
    groups = {}
    for e in entries:
        groups.setdefault(e["ref"], []).append(e)
    return {r: es for r, es in groups.items() if len(es) > 1}


FOOTPRINT_SELECTORS = ("ref", "id", "uuid")


def resolve_footprint(entries, kind, want):
    """The one entry a typed selector names: kind "ref" matches designators
    only, "id" the snapshot primitiveId only, "uuid" the footprint uuid only
    (namespaces never mix: a designator may read "ref:C1" or "uuid:..."). Returns
    (entry, None) or (None, why); why is "missing" or "ambiguous: <ids>"."""
    field = {"ref": "ref", "id": "key", "uuid": "uuid"}[kind]
    hits = [e for e in entries if e[field] == want]
    if not hits:
        return None, "missing"
    if len(hits) > 1:
        return None, "ambiguous: %d footprints (%s); address one by its id" % (len(hits), ", ".join(e["key"] for e in hits))
    return hits[0], None


def footprint_selector(op):
    """(kind, value, problem) of an op naming one footprint by exactly one
    of "ref" (designator), "id" (primitiveId) or "uuid"."""
    given = [k for k in FOOTPRINT_SELECTORS if op.get(k) is not None]
    if len(given) != 1:
        return None, None, "give exactly one of ref / id / uuid (got %s)" % (", ".join(given) or "none")
    k = given[0]
    if not isinstance(op[k], str) or not op[k]:
        return None, None, "%s %r is not a non-empty string" % (k, op[k])
    return k, op[k], None


def field_id(key, which):
    return key + "#" + which


def snapshot(board):
    snap = {"components": [], "partial": [], "source": "kicad"}
    notes = snap["partial"]
    entries, dups = comp_keys(board)
    if dups:
        notes.append("%d footprint(s) share a uuid with another: their ids are ref:<designator> (or fp:<uuid>:<n>)" % dups)
    # Shared designators stay separate list entries (own primitiveId and
    # uuid); duplicateDesignators names them so no consumer has to guess.
    dup = duplicate_refs(entries)
    if dup:
        snap["duplicateDesignators"] = [{"designator": r, "ids": [e["key"] for e in dup[r]], "placeholder": is_placeholder(r)}
                                        for r in sorted(dup)]
        notes.append("designator(s) on more than one footprint: %s — address these footprints by primitiveId, not designator"
                     % ", ".join("%s x%d" % (r, len(dup[r])) for r in sorted(dup)))
    # Placeholders (a lone REF** logo is common) are listed, not a "partial"
    # degradation: the snapshot itself is complete.
    holder = sorted({e["ref"] for e in entries if is_placeholder(e["ref"])})
    if holder:
        snap["placeholderDesignators"] = holder
    holes = []
    for e in entries:
        fp, ref = e["fp"], e["ref"]
        x, y = xy(fp.GetPosition())
        comp = {
            "primitiveId": e["key"],
            "uuid": e["uuid"],
            "designator": ref,
            "name": fp.GetValue(),
            "device": fp.GetValue(),
            "value": fp.GetValue(),
            "footprint": fp.GetFPIDAsString(),
            "layer": 2 if fp.IsFlipped() else 1,
            "side": "bottom" if fp.IsFlipped() else "top",
            "x": x,
            "y": y,
            "rotation": round(fp.GetOrientationDegrees() % 360.0, 6),
            "locked": bool(fp.IsLocked()),
            "bbox": box_mil(fp.GetBoundingBox(False)),
            "pads": [],
        }
        if ref in dup:
            comp["duplicateDesignator"] = True
        lc = local_clearance(fp)
        if lc is not None:
            comp["localClearance"] = lc
        ties = net_tie_groups(fp)
        if ties:
            comp["netTiePadGroups"] = ties
        if is_placeholder(ref):
            comp["placeholder"] = True
        lcsc = lcsc_of(fp)
        if lcsc:
            comp["lcsc"] = lcsc
        try:
            fp.BuildCourtyardCaches()
            cy = fp.GetCourtyard(pcbnew.B_CrtYd if fp.IsFlipped() else pcbnew.F_CrtYd)
            if cy.OutlineCount() > 0:
                comp["courtyard"] = box_mil(cy.BBox())
        except Exception:
            pass
        for p in fp.Pads():
            attr = p.GetAttribute()
            px, py = xy(p.GetPosition())
            size = p.GetSize(pcbnew.F_Cu) if hasattr(p, "GetSize") else p.GetSize()
            drill = p.GetDrillSize()
            if attr == pcbnew.PAD_ATTRIB_NPTH:
                hole = {"owner": ref, "componentId": comp["primitiveId"], "sourceId": p.m_Uuid.AsString(), "x": px, "y": py}
                if drill.x == drill.y:
                    hole["shape"], hole["dia"] = "circle", mil(drill.x)
                else:
                    # Slot: its bounding box as a conservative envelope.
                    poly = chain_points(p.GetEffectiveHoleShape().Outline(0)) if hasattr(p.GetEffectiveHoleShape(), "Outline") else []
                    if len(poly) < 3:
                        r = mil(max(drill.x, drill.y)) / 2
                        poly = [[px - r, py - r], [px + r, py - r], [px + r, py + r], [px - r, py + r]]
                    hole["shape"], hole["points"], hole["envelope"] = "polygon", poly, True
                holes.append(hole)
                continue
            if attr == pcbnew.PAD_ATTRIB_PTH:
                lid = 12
            elif p.IsOnLayer(pcbnew.F_Cu):
                lid = 1
            elif p.IsOnLayer(pcbnew.B_Cu):
                lid = 2
            else:
                continue  # no copper (fiducial on mask only, etc.)
            bb = box_mil(p.GetBoundingBox())
            kind = pad_kind(p.GetShape(pcbnew.F_Cu))
            w, h, rot = mil(size.x), mil(size.y), round(p.GetOrientationDegrees() % 360.0, 6)
            if kind == "POLYGON":
                w, h, rot = bb["maxX"] - bb["minX"], bb["maxY"] - bb["minY"], 0.0
            pad = {
                "primitiveId": p.m_Uuid.AsString(),
                "padNumber": p.GetNumber(),
                "net": p.GetNetname(),
                "layer": lid,
                "x": px,
                "y": py,
                "width": round(bb["maxX"] - bb["minX"], 4),
                "height": round(bb["maxY"] - bb["minY"], 4),
                "rotation": rot,
                "shape": [kind, w, h],
            }
            if lid == 12:
                pad["holeDiameter"] = mil(min(drill.x, drill.y))
            lc = local_clearance(p)
            if lc is not None:
                pad["localClearance"] = lc
            comp["pads"].append(pad)
        snap["components"].append(comp)
    if holes:
        snap["footprintHoles"] = holes

    # Board outline (Edge.Cuts); arcs are approximated by KiCad.
    ps = pcbnew.SHAPE_POLY_SET()
    ok = False
    try:
        ok = board.GetBoardPolygonOutlines(ps, False)
    except TypeError:
        ok = board.GetBoardPolygonOutlines(ps)
    fills = []
    if ok and ps.OutlineCount() > 0:
        best, area = 0, -1.0
        for i in range(ps.OutlineCount()):
            a = abs(ps.Outline(i).Area())
            if a > area:
                best, area = i, a
        pts = chain_points(ps.Outline(best))
        fmt = "polyline" if ps.OutlineCount() == 1 else "largest-of:%d" % ps.OutlineCount()
        snap["outline"] = {"bbox": bbox_of(pts), "points": pts, "source": "polygon", "format": fmt}
        for j in range(ps.HoleCount(best)):
            hp = chain_points(ps.Hole(best, j))
            fills.append({"primitiveId": "edgecut-%d" % j, "layer": 12, "net": "", "source": source_of(hp), "bbox": bbox_of(hp), "geometryAvailable": True})
    else:
        bb = board.GetBoardEdgesBoundingBox()
        if bb.GetWidth() > 0:
            snap["outline"] = {"bbox": box_mil(bb), "source": "bbox", "format": "no-closed-edge-cuts"}
        notes.append("board outline: Edge.Cuts is not one closed polygon — edge distances use the AABB")

    n = board.GetCopperLayerCount()
    snap["copperLayers"] = n
    ds = board.GetDesignSettings()
    dn = ds.m_NetSettings.GetDefaultNetclass()
    clr = max(ds.m_MinClearance, dn.GetClearance())
    snap["rules"] = {
        "clearanceMil": mil(clr),
        "clearanceTrackTrackMil": mil(clr),
        "trackWidthMil": mil(dn.GetTrackWidth()),
        "powerWidthMil": mil(dn.GetTrackWidth()),
        "trackWidthMinMil": mil(ds.m_TrackMinWidth),
        # A new via must satisfy both the Default netclass and the board's own
        # minimums (min hole, min via diameter, min annular ring).
        "viaDrillMil": mil(via_floor(ds, dn.GetViaDiameter(), dn.GetViaDrill())[1]),
        "viaDiameterMil": mil(via_floor(ds, dn.GetViaDiameter(), dn.GetViaDrill())[0]),
        "minViaDrillMil": mil(ds.m_MinThroughDrill),
        "minViaDiameterMil": mil(ds.m_ViasMinSize),
        "minViaAnnularMil": mil(ds.m_ViasMinAnnularWidth),
        "copperToEdgeMil": mil(ds.m_CopperEdgeClearance),
        "holeToHoleMil": mil(ds.m_HoleToHoleMin),
        "source": "kicad",
    }
    classes = []
    for name, nc in ds.m_NetSettings.GetNetclasses().items():
        classes.append({"name": str(name), "trackWidthMil": mil(nc.GetTrackWidth()) if nc.HasTrackWidth() else None,
                        "clearanceMil": mil(nc.GetClearance()) if nc.HasClearance() else None})
    snap["netclasses"] = sorted(classes, key=lambda c: c["name"])
    nets = {}
    for name, net in board.GetNetsByName().items():
        name = str(name)
        if not name:
            continue
        try:
            nets[name] = ds.m_NetSettings.GetEffectiveNetClass(name).GetName()
        except Exception:
            nets[name] = ""
    snap["netClassOf"] = nets
    layer_types = {}
    for l in board.GetEnabledLayers().CuStack():
        layer_types[str(layer_id(board, l))] = {"name": kicad_layer_name(l), "type": int(board.GetLayerType(l))}
    snap["kicadLayers"] = layer_types

    lines, arcs, vias = [], [], []
    for t in board.GetTracks():
        tt = t.Type()
        if tt == pcbnew.PCB_VIA_T:
            vx, vy = xy(t.GetPosition())
            vias.append({"primitiveId": t.m_Uuid.AsString(), "net": t.GetNetname(), "x": vx, "y": vy,
                         "diameter": mil(t.GetWidth(pcbnew.F_Cu) if t.GetViaType() == pcbnew.VIATYPE_THROUGH else t.GetFrontWidth()),
                         "holeDiameter": mil(t.GetDrillValue()), "locked": bool(t.IsLocked()),
                         "fromLayer": layer_id(board, t.TopLayer()), "toLayer": layer_id(board, t.BottomLayer())})
            continue
        lid = layer_id(board, t.GetLayer())
        sx, sy = xy(t.GetStart())
        ex, ey = xy(t.GetEnd())
        rec = {"primitiveId": t.m_Uuid.AsString(), "net": t.GetNetname(), "layer": lid,
               "startX": sx, "startY": sy, "endX": ex, "endY": ey, "lineWidth": mil(t.GetWidth()), "locked": bool(t.IsLocked())}
        if tt == pcbnew.PCB_ARC_T:
            mx, my = xy(t.GetMid())
            rec["midX"], rec["midY"] = mx, my
            rec["arcAngle"] = arc_angle((sx, sy), (mx, my), (ex, ey))
            arcs.append(rec)
        else:
            lines.append(rec)
    pours, poured, regions = [], [], []
    for z in board.Zones():
        zid = z.m_Uuid.AsString()
        layers = [l for l in z.GetLayerSet().CuStack()]
        outline = []
        if z.Outline().OutlineCount() > 0:
            outline = chain_points(z.Outline().Outline(0))
        if z.GetIsRuleArea():
            rules = []
            if z.GetDoNotAllowFootprints():
                rules.append(2)
            if z.GetDoNotAllowTracks() or z.GetDoNotAllowVias():
                rules.append(5)
            if z.GetDoNotAllowZoneFills():
                rules.append(7)
            regions.append({"primitiveId": zid, "name": z.GetZoneName(), "layer": 12 if len(layers) != 1 else layer_id(board, layers[0]),
                            "layers": [layer_id(board, l) for l in layers], "ruleType": rules, "source": source_of(outline),
                            "bbox": bbox_of(outline) if outline else None, "geometryAvailable": bool(outline)})
            continue
        for l in layers:
            lid = layer_id(board, l)
            pours.append({"primitiveId": zid, "name": z.GetZoneName(), "net": z.GetNetname(), "layer": lid,
                          "source": source_of(outline), "geometryAvailable": bool(outline)})
            if z.IsFilled():
                f = poly_set_fills(z.GetFilledPolysList(l))
                if f:
                    poured.append({"pourPrimitiveId": zid, "net": z.GetNetname(), "layer": lid, "fills": f})
    snap["copper"] = {
        "availability": {k: "available" for k in ("routing", "vias", "pours", "poured", "regions", "fills")},
        "lines": lines, "arcs": arcs, "arcsAvailable": True, "vias": vias,
        "pours": pours, "poured": poured, "regions": regions, "fills": fills,
    }
    snap["routedLines"] = len(lines) + len(arcs)
    rep_ids = sorted(u for u, ts in copper_by_uuid(board).items() if len(ts) > 1)
    if rep_ids:
        snap["copper"]["duplicateIds"] = rep_ids
        notes.append("%d copper id(s) shared by several tracks/vias (%s): edits by those ids are refused"
                     % (len(rep_ids), ", ".join(rep_ids[:5]) + (", ..." if len(rep_ids) > 5 else "")))
    try:
        snap["silk"] = silk_texts(board, entries)
    except Exception as e:  # silk is optional for the copper consumers
        notes.append("silkscreen unreadable: %s" % e)
    snap["partial"] = notes
    if not notes:
        del snap["partial"]
    return snap


def silk_layer(l):
    """pcbpilot silk layer id: 3 = F.Silkscreen, 4 = B.Silkscreen, 0 = other."""
    if l == pcbnew.F_SilkS:
        return 3
    if l == pcbnew.B_SilkS:
        return 4
    return 0


def text_index(board, entries):
    """Every text silk_texts() reports, as [id, text, kind, key, entry]
    (entry = the owning footprint_index() entry, None for board text). Ids:
    "<component id>#ref" / "#value" for the fields; a graphic text's uuid,
    or "<component id | board>#text:<uuid>:<n>" when the uuid repeats (a
    duplicated footprint carries its texts' uuids along). edit addresses
    texts by these same ids."""
    items = []
    for e in entries:
        fp, k = e["fp"], e["key"]
        items.append([field_id(k, "ref"), fp.Reference(), "attribute", "Designator", e])
        items.append([field_id(k, "value"), fp.Value(), "attribute", "Device", e])
        for item in fp.GraphicalItems():
            if item.GetClass() in ("PCB_TEXT", "FP_TEXT") and silk_layer(item.GetLayer()):
                items.append([None, item, "string", "", e])
    for item in board.GetDrawings():
        if item.GetClass() == "PCB_TEXT" and silk_layer(item.GetLayer()):
            items.append([None, item, "string", "", None])
    n, nth = {}, {}
    for it in items:
        if it[0] is None:
            u = it[1].m_Uuid.AsString()
            n[u] = n.get(u, 0) + 1
    for it in items:
        if it[0] is None:
            u = it[1].m_Uuid.AsString()
            if n[u] == 1:
                it[0] = u
            else:
                base = "%s#text:%s" % (it[4]["key"] if it[4] else "board", u)
                nth[base] = nth.get(base, 0) + 1
                it[0] = "%s:%d" % (base, nth[base])
    return items


def silk_texts(board, entries):
    """Silkscreen texts in the pcbpilot pcbSilkText shape (Go field names):
    every footprint reference/value field and footprint/board text
    (text_index). Layer 3 = F.Silkscreen, 4 = B.Silkscreen, 0 = not on silk
    (then Hidden)."""
    out = []
    for tid, t, kind, key, e in text_index(board, entries):
        bb = box_mil(t.GetBoundingBox())
        layer = silk_layer(t.GetLayer())
        visible = t.IsVisible() if hasattr(t, "IsVisible") else True
        r = {
            "ID": tid, "Kind": kind, "Key": key, "Text": t.GetShownText(False) if hasattr(t, "GetShownText") else t.GetText(),
            "Layer": layer, "Mirror": bool(t.IsMirrored()), "Reverse": False,
            "Rotation": round(t.GetTextAngleDegrees() % 360.0, 4),
            "FontSize": mil(t.GetTextHeight()), "LineWidth": mil(t.GetTextThickness()),
            "X": bb["minX"], "Y": bb["minY"],
            "BBox": {"MinX": bb["minX"], "MinY": bb["minY"], "MaxX": bb["maxX"], "MaxY": bb["maxY"]},
            "Hidden": (not visible) or layer == 0,
        }
        if e is not None:
            r["CompID"] = e["key"]
            r["CompLayer"] = 2 if e["fp"].IsFlipped() else 1
        out.append(r)
    return out


def arc_angle(s, m, e):
    """Signed sweep (degrees, CCW > 0 in y-up) of the arc s→m→e."""
    ax, ay = s
    bx, by = m
    cx, cy = e
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    if abs(d) < 1e-12:
        return 0.0
    ux = ((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay) + (cx * cx + cy * cy) * (ay - by)) / d
    uy = ((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx) + (cx * cx + cy * cy) * (bx - ax)) / d
    a0 = math.atan2(ay - uy, ax - ux)
    a1 = math.atan2(by - uy, bx - ux)
    a2 = math.atan2(cy - uy, cx - ux)

    def ccw(a, b):
        return (b - a) % (2 * math.pi)

    sweep = ccw(a0, a2)
    if ccw(a0, a1) > sweep:  # the mid point is not on the CCW path: clockwise
        sweep -= 2 * math.pi
    return round(math.degrees(sweep), 6)


