# bridge.py — pcbpilot's KiCad bridge. Run with KiCad's bundled Python
# (the one that can `import pcbnew`). Embedded into the pcbpilot binary
# (internal/kicad, go:embed) and written to a cache file before each run.
#
# Every subcommand prints exactly one result line on stdout:
#
#     PCBPILOT_JSON:{...}
#
# pcbnew prints debug noise (wx asserts) on stderr and occasionally on
# stdout, so the Go side reads only the line with that prefix. A failure is
# {"ok": false, "error": "..."} with exit status 1.
#
# Units: every length in the output is mil, y-UP (y = -y_kicad), to match
# pcbpilot's board snapshot (internal/app/pcb_board_snapshot.go). Rotations
# stay in degrees CCW (negating y keeps the visual sense of a rotation).
# Copper layer ids follow pcbpilot's EasyEDA numbering so the existing
# gates work unchanged: F.Cu = 1, B.Cu = 2, InN.Cu = 14+N, through-hole = 12.
#
# Only KiCad's public Python API (pcbnew) is used.
#
# Subcommands:
#   snapshot PCB                    board snapshot JSON (result.snapshot)
#   netclasses PCB REQS.json OUT    write intent widths/clearances as netclasses
#   ripup PCB OUT                   delete unlocked tracks and vias
#   dsn PCB OUT.dsn                 ExportSpecctraDSN
#   ses PCB IN.ses OUT.kicad_pcb    ImportSpecctraSES + zone fill + save
#   fill PCB                        zone fill + save in place
#   rules PCB RULES.json OUT        design rules + Default netclass (mil)
#   pours PCB SPEC.json OUT         board-outline copper pours + fill
#   edit PCB OPS.json OUT           track widths, vias, stubs, silk texts + fill
#   sync-read PCB                   pcb-sync inventory (mm, KiCad y-down)
#   fp-info SPEC.json               library footprints: pads + courtyard box
#   sync-apply PCB|- PLAN.json OUT  apply a pcb-sync plan; OUT in $PCBPILOT_STAGE_DIR
#   rules-read PCB                  effective netclass + sizes per net (nm), classes, sizes
#   rules-probe PCB SPEC.json OUT   add exact-width probe tracks (kicad rules verification)
#
# Writes are all or nothing: edit and pours check every net, layer, item id
# and footprint first; an unknown net, a missing id or a designator on more
# than one footprint rejects the operation ({"ok": false, "problems": [...]})
# and nothing is saved. Footprints are keyed by footprint_index(), never by
# designator alone (several REF** logos, two H1 holes).

