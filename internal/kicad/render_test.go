// svgDoc is a small kicad-cli-shaped SVG: plot title, one styled group.
func svgDoc(title, body string) string {
	return "<?xml version=\"1.0\" standalone=\"no\"?>\r\n <!DOCTYPE svg PUBLIC \"-//W3C//DTD SVG 1.1//EN\" \r\n \"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd\"> \r\n" +
		"<svg\r\n  xmlns=\"http://www.w3.org/2000/svg\"\r\n  version=\"1.1\"\r\n  width=\"10.0000mm\" height=\"5.0000mm\" viewBox=\"0.0000 0.0000 10.0000 5.0000\">\r\n" +
		"<title>" + title + " </title>\r\n  <desc>Image generated by Eeschema-SVG </desc>\r\n" +
		"<g style=\"fill:none; \r\nstroke:#840000; stroke-width:0.1524;\">\r\n" + body + "</g>\r\n</svg>\r\n"
}

// Two plots of one drawing differ only in plot date, line ends, the temp
// directory and "-0": normalised they are byte-identical.
func TestNormalizeSVGDeterministic(t *testing.T) {
	tmpA, tmpB := filepath.Join(t.TempDir(), "a"), filepath.Join(t.TempDir(), "b")
	a := svgDoc("SVG Image created as p.svg date 2026-10-27T03:22:11", "<path d=\"M-0.0000 1.0000\nL2.0000 -0.5000\n\" />\n<text x=\"1\">File: "+tmpA+string(os.PathSeparator)+"p.kicad_sch</text>\n")
	b := svgDoc("SVG Image created as p.svg date 2026-10-27T03:22:25", "<path d=\"M0.0000 1.0000\nL2.0000 -0.5000\n\" />\n<text x=\"1\">File: "+filepath.ToSlash(tmpB)+"/p.kicad_sch</text>\n")
	na, nb := NormalizeSVG([]byte(a), tmpA), NormalizeSVG([]byte(b), tmpB)
	if string(na) != string(nb) {
		t.Fatalf("not identical:\n%s\n---\n%s", na, nb)
	}
	s := string(na)
	for _, bad := range []string{"\r", "date 2026", tmpA, " </title>"} {
		if strings.Contains(s, bad) {
			t.Errorf("normalised SVG still holds %q", bad)
		}
	}
	for _, keep := range []string{"-0.5000", "File: p.kicad_sch", "<title>SVG Image created as p.svg</title>"} {
		if !strings.Contains(s, keep) {
			t.Errorf("normalised SVG lost %q:\n%s", keep, s)
		}
	}
	if again := NormalizeSVG(na, tmpA); string(again) != s {
		t.Error("NormalizeSVG is not idempotent")
	}
}

func writeSVG(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte(svgDoc("SVG Image created as "+name, body)), 0o644); err != nil {
		t.Fatal(err)
	}
}

// The compare verdicts: identical / changed (counted structurally) /
// reordered / added / removed / unreadable, and the tri-state verdict.
func TestCompareRenders(t *testing.T) {
	root := t.TempDir()
	base, cur := filepath.Join(root, "base"), filepath.Join(root, "cur")
	p1, p2, p3 := `<path d="M1 1 L2 2" />`+"\n", `<path d="M3 3 L4 4" />`+"\n", `<circle cx="1" cy="1" r="0.5" />`+"\n"
	writeSVG(t, base, "same.svg", p1+p2)
	writeSVG(t, cur, "same.svg", p1+p2)
	writeSVG(t, base, "moved.svg", p1+p2+p3)
	writeSVG(t, cur, "moved.svg", p1+`<path d="M3 3.5 L4 4.5" />`+"\n"+p3)
	writeSVG(t, base, "order.svg", p1+p2)
	writeSVG(t, cur, "order.svg", p2+p1)
	writeSVG(t, base, "gone.svg", p1)
	writeSVG(t, cur, "new.svg", p1)
	// A baseline written before normalisation (plot date, CRLF) still matches.
	old := svgDoc("SVG Image created as dated.svg date 2025-01-02T03:04:05", p1)
	_ = os.WriteFile(filepath.Join(base, "dated.svg"), []byte(old), 0o644)
	writeSVG(t, cur, "dated.svg", p1)
	_ = os.WriteFile(filepath.Join(cur, "x-3d-top.png"), []byte("png"), 0o644)

	r := CompareRenders(base, cur)
	if r.Verdict != gate.Fail {
		t.Fatalf("verdict %s, want fail", r.Verdict)
	}
	want := map[string]string{"same.svg": "identical", "dated.svg": "identical", "moved.svg": "changed", "order.svg": "changed",
		"gone.svg": "removed", "new.svg": "added"}
	got := map[string]RenderFileDiff{}
	for _, f := range r.Files {
		got[f.File] = f
		if want[f.File] != f.Status {
			t.Errorf("%s: %s, want %s (%s)", f.File, f.Status, want[f.File], f.Detail)
		}
	}
	if m := got["moved.svg"]; m.ElementsAdded != 1 || m.ElementsRemoved != 1 || m.ChangedElements != 2 || m.Reordered || len(m.Samples) != 2 {
		t.Errorf("moved: %+v", m)
	}
	if o := got["order.svg"]; !o.Reordered || o.ChangedElements != 0 {
		t.Errorf("order: %+v", o)
	}
	if len(r.Ignored) != 1 || r.Ignored[0] != "x-3d-top.png" {
		t.Errorf("ignored %v", r.Ignored)
	}

	// Only identical files: pass. A file that does not parse: cannot-check.
	okBase, okCur := filepath.Join(root, "ok1"), filepath.Join(root, "ok2")
	writeSVG(t, okBase, "a.svg", p1)
	writeSVG(t, okCur, "a.svg", p1)
	if v := CompareRenders(okBase, okCur).Verdict; v != gate.Pass {
		t.Errorf("identical dirs: %s", v)
	}
	_ = os.WriteFile(filepath.Join(okBase, "b.svg"), []byte("<svg><path></svg>"), 0o644)
	_ = os.WriteFile(filepath.Join(okCur, "b.svg"), []byte("<svg><path d=\"\"></svg>"), 0o644)
	if r := CompareRenders(okBase, okCur); r.Verdict != gate.CannotCheck || r.Counts["unreadable"] != 1 {
		t.Errorf("unparsable file: %s %v", r.Verdict, r.Counts)
	}
	if r := CompareRenders(filepath.Join(root, "missing"), okCur); r.Verdict != gate.CannotCheck || r.Fix == "" {
		t.Errorf("missing baseline: %s %q", r.Verdict, r.Fix)
	}
}

// Group style is part of an element: recolouring a layer is a change even
// when every path keeps its coordinates.
func TestSVGElementsCarryGroupStyle(t *testing.T) {
	a, err := SVGElements([]byte(`<svg><g style="stroke:#840000"><path d="M1 1"/></g></svg>`))
	if err != nil {
		t.Fatal(err)
	}
	b, _ := SVGElements([]byte(`<svg><g style="stroke:#008400"><path d="M1 1"/></g></svg>`))
	if len(a) != 2 || a[1] == b[1] {
		t.Fatalf("style not part of the element: %q vs %q", a, b)
	}
	c, _ := SVGElements([]byte(`<svg><g style="stroke:#840000"><path   d="M1
 1"/></g></svg>`))
	if a[1] != c[1] {
		t.Errorf("attribute whitespace changed the element: %q vs %q", a[1], c[1])
	}
}

// A non-empty --out that no render wrote is refused; a render's own output
// is cleared of exactly the files its manifest lists.
func TestPrepareRenderOut(t *testing.T) {
	dir := t.TempDir()
	_ = os.WriteFile(filepath.Join(dir, "notes.txt"), []byte("mine"), 0o644)
	if err := prepareRenderOut(dir); err == nil {
		t.Fatal("foreign directory accepted")
	} else if e, ok := err.(*RenderError); !ok || e.Code != "RENDER_OUT_NOT_EMPTY" || e.Fix == "" {
		t.Fatalf("error %v", err)
	}
	_ = os.WriteFile(filepath.Join(dir, "old.svg"), []byte("<svg/>"), 0o644)
	_ = os.WriteFile(filepath.Join(dir, RenderManifestName), []byte(`{"files":[{"file":"old.svg"},{"file":"../escape.svg"}]}`), 0o644)
	if err := prepareRenderOut(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(dir, "old.svg")); !os.IsNotExist(err) {
		t.Error("listed file kept")
	}
	if _, err := os.Stat(filepath.Join(dir, "notes.txt")); err != nil {
		t.Error("unlisted file deleted")
	}
}

func TestRenderPixels(t *testing.T) {
	for _, c := range []struct {
		mm   float64
		dpi  int
		want int
	}{{160.02, 100, 630}, {0, 150, 0}, {1, 10, 64}, {5000, 600, 8000}} {
		if got := renderPixels(c.mm, c.dpi); got != c.want {
			t.Errorf("renderPixels(%v, %d) = %d, want %d", c.mm, c.dpi, got, c.want)
		}
	}
}
