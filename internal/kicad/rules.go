package kicad

// rules.go — the KiCad side of `pcbpilot kicad rules`: the netclasses
// request (shared with kicad route), the readback of what KiCad resolves
// per net (bridge rules-read), probe tracks for DRC verification (bridge
// rules-probe), the board stackup's copper thickness and a reader for
// .kicad_dru custom rules.

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// Owned markers. The route block is what bridge netclasses writes (also for
// kicad route); the rules block is what kicad rules adds on top of it, right
// before the route block (so a later route run, which re-appends its block
// at the end, leaves the order unchanged).
const (
	DRURouteBegin = "# pcbpilot:begin (generated by pcbpilot kicad netclasses; do not edit inside this block)"
	DRURouteEnd   = "# pcbpilot:end"
	DRURulesBegin = "# pcbpilot-rules:begin (generated by pcbpilot kicad rules; do not edit inside this block)"
	DRURulesEnd   = "# pcbpilot-rules:end"
	// DRURulesPrefix starts the name of every rule kicad rules owns.
	DRURulesPrefix = "pcbpilot-rules "
	// DRURoutePrefix starts the name of every rule bridge netclasses owns.
	DRURoutePrefix = "pcbpilot "
)

// SizeSet is a set of KiCad pre-defined sizes in nm.
type SizeSet struct {
	Tracks []int64    `json:"tracks"`
	Vias   [][2]int64 `json:"vias"`
}

// NetclassRequest is one bridge netclasses request. Sizes nil leaves the
// pre-defined sizes alone (kicad route); non-nil (kicad rules) replaces
// the sizes an earlier run owned (Sizes itself) with the new classes'.
type NetclassRequest struct {
	Nets      map[string]NetRequirement
	Isolation []map[string]any
	Edges     []map[string]any
	Sizes     *SizeSet
}

// Body is the request JSON object. Without Sizes it is byte for byte the
// request NetclassesIso has always written.
func (r NetclassRequest) Body() map[string]any {
	b := map[string]any{"pcbpilotReqs": 2, "nets": r.Nets, "isolation": r.Isolation, "edges": r.Edges}
	if r.Sizes != nil {
		owned := map[string]any{"tracks": nonNilInts(r.Sizes.Tracks), "vias": nonNilPairs(r.Sizes.Vias)}
		b["predefinedSizes"] = map[string]any{"owned": owned}
	}
	return b
}

func nonNilInts(v []int64) []int64 {
	if v == nil {
		return []int64{}
	}
	return v
}

func nonNilPairs(v [][2]int64) [][2]int64 {
	if v == nil {
		return [][2]int64{}
	}
	return v
}

// ClassNM are a written class's values in integer nm (the bridge's "nm").
type ClassNM struct {
	Track       int64 `json:"track"`
	Inner       int64 `json:"inner"`
	Min         int64 `json:"min"`
	Clearance   int64 `json:"clearance"`
	ViaDiameter int64 `json:"viaDiameter"`
	ViaDrill    int64 `json:"viaDrill"`
}

// NetclassClassNM is one class of a netclasses result with its nm values.
type NetclassClassNM struct {
	NetClass
	NM ClassNM `json:"nm"`
}

// SizesResult is the pre-defined sizes a netclasses run with Sizes left.
type SizesResult struct {
	Tracks []int64    `json:"tracks"`
	Vias   [][2]int64 `json:"vias"`
	Owned  SizeSet    `json:"owned"`
}

// NetclassFull is a netclasses result with the nm values and sizes.
type NetclassFull struct {
	NetclassResult
	ClassesNM []NetclassClassNM `json:"-"`
	Sizes     *SizesResult      `json:"sizes,omitempty"`
}

// NetclassesReq runs bridge netclasses with req on pcb, writing out (+ its
// .kicad_pro / .kicad_dru).
func (t *Tools) NetclassesReq(pcb string, req NetclassRequest, out string) (*NetclassFull, error) {
	path := strings.TrimSuffix(out, filepath.Ext(out)) + "-reqs.json"
	b, err := json.MarshalIndent(req.Body(), "", "  ")
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(path, b, 0o644); err != nil {
		return nil, err
	}
	raw, err := t.RunBridge("netclasses", pcb, path, out)
	if err != nil {
		return nil, err
	}
	return DecodeNetclassFull(raw)
}

// DecodeNetclassFull decodes a bridge netclasses result.
func DecodeNetclassFull(raw []byte) (*NetclassFull, error) {
	var res NetclassFull
	if err := json.Unmarshal(raw, &res.NetclassResult); err != nil {
		return nil, err
	}
	var extra struct {
		Classes []NetclassClassNM `json:"classes"`
		Sizes   *SizesResult      `json:"sizes"`
	}
	if err := json.Unmarshal(raw, &extra); err != nil {
		return nil, err
	}
	res.ClassesNM, res.Sizes = extra.Classes, extra.Sizes
	return &res, nil
}

// EffectiveNM is what KiCad resolves for one net (nm): the effective class
// (KiCad's composite name, "PP1_W10,PPD_MAINS") and its sizes.
type EffectiveNM struct {
	Class       string `json:"class"`
	Track       int64  `json:"track"`
	Clearance   int64  `json:"clearance"`
	ViaDiameter int64  `json:"viaDiameter"`
	ViaDrill    int64  `json:"viaDrill"`
}

// ReadClass is one netclass of a project as KiCad loaded it (nil = the
// class does not set that value).
type ReadClass struct {
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
	Priority    *int   `json:"priority,omitempty"`
	Track       *int64 `json:"track,omitempty"`
	Clearance   *int64 `json:"clearance,omitempty"`
	ViaDiameter *int64 `json:"viaDiameter,omitempty"`
	ViaDrill    *int64 `json:"viaDrill,omitempty"`
}

// Minimums are a board's own design-rule minimums (nm).
type Minimums struct {
	Track       int64 `json:"track"`
	Clearance   int64 `json:"clearance"`
	ViaDiameter int64 `json:"viaDiameter"`
	ViaDrill    int64 `json:"viaDrill"`
	ViaAnnular  int64 `json:"viaAnnular"`
	Edge        int64 `json:"edge"`
}

// RulesReadback is bridge rules-read: what KiCad resolves on a board.
type RulesReadback struct {
	KiCadVersion string                 `json:"kicadVersion"`
	CopperLayers int                    `json:"copperLayers"`
	Minimums     Minimums               `json:"minimums"`
	Default      EffectiveNM            `json:"default"`
	Classes      []ReadClass            `json:"classes"`
	Patterns     [][2]string            `json:"patterns"`
	Nets         map[string]EffectiveNM `json:"nets"`
	Sizes        SizeSet                `json:"sizes"`
}

// RulesRead runs bridge rules-read on pcb (read only).
func (t *Tools) RulesRead(pcb string) (*RulesReadback, error) {
	raw, err := t.RunBridge("rules-read", pcb)
	if err != nil {
		return nil, err
	}
	var r RulesReadback
	if err := json.Unmarshal(raw, &r); err != nil {
		return nil, fmt.Errorf("kicad bridge rules-read: %w", err)
	}
	return &r, nil
}

// ProbeTrack is one probe track (mil, y-up; exact nm width).
type ProbeTrack struct {
	Net     string  `json:"net"`
	Layer   int     `json:"layer"`
	StartX  float64 `json:"startX"`
	StartY  float64 `json:"startY"`
	EndX    float64 `json:"endX"`
	EndY    float64 `json:"endY"`
	WidthNm int64   `json:"widthNm"`
}

// RulesProbe writes pcb plus the probe tracks to out (a scratch copy) and
// returns the tracks' uuids in order.
func (t *Tools) RulesProbe(pcb string, tracks []ProbeTrack, out string) ([]string, error) {
	path := strings.TrimSuffix(out, filepath.Ext(out)) + "-probe.json"
	b, err := json.MarshalIndent(map[string]any{"tracks": tracks}, "", "  ")
	if err != nil {
		return nil, err
	}
	if err := os.WriteFile(path, b, 0o644); err != nil {
		return nil, err
	}
	raw, err := t.RunBridge("rules-probe", pcb, path, out)
	if err != nil {
		return nil, err
	}
	var res struct {
		IDs []string `json:"ids"`
	}
	if err := json.Unmarshal(raw, &res); err != nil {
		return nil, err
	}
	if len(res.IDs) != len(tracks) {
		return nil, fmt.Errorf("kicad bridge rules-probe: %d id(s) for %d track(s)", len(res.IDs), len(tracks))
	}
	return res.IDs, nil
}

// ── stackup ────────────────────────────────────────────────────────────────

// StackupCopper is one copper layer of a board's stackup.
type StackupCopper struct {
	Layer       string  `json:"layer"`
	ThicknessMm float64 `json:"thicknessMm"` // 0 = the stackup gives none
}

// ReadStackupCopper returns the copper layers of the board's (setup
// (stackup …)) in stackup order; nil when the board has no stackup.
func ReadStackupCopper(board []byte) ([]StackupCopper, error) {
	root, err := parseSexpr(board)
	if err != nil {
		return nil, err
	}
	if root.head() != "kicad_pcb" {
		return nil, fmt.Errorf("not a kicad_pcb file (root %q)", root.head())
	}
	st := root.child("setup").child("stackup")
	if st == nil {
		return nil, nil
	}
	var out []StackupCopper
	for _, l := range st.children("layer") {
		if strings.ToLower(l.child("type").arg(0)) != "copper" {
			continue
		}
		c := StackupCopper{Layer: l.arg(0)}
		if v, err := strconv.ParseFloat(l.child("thickness").arg(0), 64); err == nil && v > 0 {
			c.ThicknessMm = v
		}
		out = append(out, c)
	}
	return out, nil
}

// ── .kicad_dru ─────────────────────────────────────────────────────────────

// DRUConstraint is one (constraint …) of a custom rule; values in nm.
type DRUConstraint struct {
	Type string `json:"type"`
	Min  *int64 `json:"minNm,omitempty"`
	Opt  *int64 `json:"optNm,omitempty"`
	Max  *int64 `json:"maxNm,omitempty"`
	// Unparsed: a value that is not a length (an expression, an unknown unit).
	Unparsed bool `json:"unparsed,omitempty"`
}

// DRURule is one custom rule. Block: "" (the user's), "rules" or "route"
// (pcbpilot-owned blocks). Index is the rule's order in the file (later
// rules win in KiCad).
type DRURule struct {
	Name        string          `json:"name"`
	Condition   string          `json:"condition,omitempty"`
	Layer       string          `json:"layer,omitempty"`
	Constraints []DRUConstraint `json:"constraints"`
	Block       string          `json:"block,omitempty"`
	Index       int             `json:"index"`
}

// SplitDRU splits a .kicad_dru text into the user part (everything outside
// pcbpilot's blocks) and the two owned blocks (with their markers; "" when
// absent). An unterminated block is an error.
func SplitDRU(text string) (user, rules, route string, err error) {
	cut := func(s, begin, end string) (rest, block string, err error) {
		i := strings.Index(s, begin)
		if i < 0 {
			return s, "", nil
		}
		j := strings.Index(s[i:], end)
		if j < 0 {
			return s, "", fmt.Errorf("custom rules: %q has no %q", begin, end)
		}
		j += i + len(end)
		if j < len(s) && s[j] == '\n' {
			j++
		}
		return s[:i] + s[j:], s[i:j], nil
	}
	rest, rules, err := cut(text, DRURulesBegin, DRURulesEnd)
	if err != nil {
		return "", "", "", err
	}
	user, route, err = cut(rest, DRURouteBegin, DRURouteEnd)
	return user, rules, route, err
}

// ParseDRU reads every rule of a .kicad_dru text, marking the rules inside
// pcbpilot's blocks.
func ParseDRU(text string) ([]DRURule, error) {
	_, rulesBlk, routeBlk, err := SplitDRU(text)
	if err != nil {
		return nil, err
	}
	root, err := parseSexpr([]byte("(dru\n" + text + "\n)"))
	if err != nil {
		return nil, fmt.Errorf("custom rules: %w", err)
	}
	owned := map[string]string{}
	for blk, body := range map[string]string{"rules": rulesBlk, "route": routeBlk} {
		if body == "" {
			continue
		}
		r, err := parseSexpr([]byte("(dru\n" + body + "\n)"))
		if err != nil {
			return nil, fmt.Errorf("custom rules (%s block): %w", blk, err)
		}
		for _, n := range r.children("rule") {
			owned[n.arg(0)] = blk
		}
	}
	var out []DRURule
	for i, n := range root.children("rule") {
		r := DRURule{Name: n.arg(0), Condition: n.child("condition").arg(0), Layer: n.child("layer").arg(0), Index: i, Block: owned[n.arg(0)]}
		for _, c := range n.children("constraint") {
			dc := DRUConstraint{Type: c.arg(0)}
			for _, k := range []string{"min", "opt", "max"} {
				v := c.child(k)
				if v == nil {
					continue
				}
				nmv, ok := DRULength(v.arg(0))
				if !ok {
					dc.Unparsed = true
					continue
				}
				switch k {
				case "min":
					dc.Min = &nmv
				case "opt":
					dc.Opt = &nmv
				default:
					dc.Max = &nmv
				}
			}
			r.Constraints = append(r.Constraints, dc)
		}
		out = append(out, r)
	}
	return out, nil
}

var reDRULen = regexp.MustCompile(`^([0-9]*\.?[0-9]+(?:[eE][-+]?[0-9]+)?)\s*(mm|mil|mils|um|in|inch)?$`)

// DRULength parses a DRU length ("0.25mm", "10mil", "0.25" = mm) to nm.
func DRULength(s string) (int64, bool) {
	m := reDRULen.FindStringSubmatch(strings.TrimSpace(s))
	if m == nil {
		return 0, false
	}
	v, err := strconv.ParseFloat(m[1], 64)
	if err != nil {
		return 0, false
	}
	scale := 1e6
	switch m[2] {
	case "mil", "mils":
		scale = 25400
	case "um":
		scale = 1000
	case "in", "inch":
		scale = 25.4e6
	}
	return int64(math.Round(v * scale)), true
}

// MmOfNm formats nm as a DRU mm length ("0.254mm").
func MmOfNm(v int64) string {
	return strconv.FormatFloat(float64(v)/1e6, 'f', -1, 64) + "mm"
}

