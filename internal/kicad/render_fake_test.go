// fakeRenderCLI plays kicad-cli's `sch export svg` / `pcb export svg` for
// the render tests (via fakeKiCadCLI). Like the real one it stamps the plot
// time into <title>; each page also prints the directory it was plotted
// from (as a ${FILEPATH}-style field would) and visible "-0" text.
// $PCBPILOT_FAKE_SVG picks a failure: skip-sub (only the root page), empty
// (pages that draw nothing), diag (a "library not found" message, exit 0),
// exit (exit 3).
func fakeRenderCLI(args []string) int {
	mode := os.Getenv("PCBPILOT_FAKE_SVG")
	if mode == "exit" {
		fmt.Fprintln(os.Stderr, "fake failure")
		return 3
	}
	if mode == "diag" {
		fmt.Println("Error: symbol library 'parts' not found")
	}
	in := args[len(args)-1]
	page := func(name string) string {
		if mode == "empty" {
			return `<svg xmlns="http://www.w3.org/2000/svg"></svg>`
		}
		return "<?xml version=\"1.0\" standalone=\"no\"?>\r\n<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"10.0000mm\" height=\"5.0000mm\">\r\n" +
			"<title>SVG Image created as " + name + " date " + time.Now().Format("2006-01-02T15:04:05.000000000") + " </title>\r\n" +
			"  <desc>Image generated by fake from " + filepath.Dir(in) + " </desc>\r\n" +
			"<g style=\"stroke:#840000\">\r\n<path d=\"M-0.0000 1.0000 L2 -0.5\" />\r\n" +
			"<text x=\"1\">Path: " + filepath.Dir(in) + string(os.PathSeparator) + filepath.Base(in) + "</text>\r\n" +
			"<text x=\"2\">-0</text>\r\n<text x=\"3\">V=-0.0</text>\r\n</g>\r\n</svg>\r\n"
	}
	if args[0] == "pcb" {
		o := ""
		for i := 0; i+1 < len(args); i++ {
			if args[i] == "-o" {
				o = args[i+1]
			}
		}
		return fakeWrite(o, page(filepath.Base(o)))
	}
	out := ""
	for i := 0; i+1 < len(args); i++ {
		if args[i] == "--output" {
			out = args[i+1]
		}
	}
	pages, _, err := ParseSchHierarchy(in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	base := strings.TrimSuffix(filepath.Base(in), filepath.Ext(in))
	for _, p := range pages {
		name := base
		if p.Name != "" {
			if mode == "skip-sub" {
				continue
			}
			name += "-" + strings.ReplaceAll(p.Name, "/", "-")
		}
		if code := fakeWrite(filepath.Join(out, name+".svg"), page(name+".svg")); code != 0 {
			return code
		}
	}
	fmt.Println("Done.")
	return 0
}

func fakeWrite(path, text string) int {
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	return 0
}

// fakeRenderCLIEnv points KICAD_CLI at the test binary acting as kicad-cli.
func fakeRenderCLIEnv(t *testing.T, mode string) {
	t.Helper()
	exe, err := os.Executable()
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("PCBPILOT_FAKE_KICAD_CLI", "1")
	t.Setenv("KICAD_CLI", exe)
	t.Setenv("PCBPILOT_FAKE_SVG", mode)
}

func copyTree(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o755)
		}
		return copyFile(p, filepath.Join(dst, rel))
	})
	if err != nil {
		t.Fatal(err)
	}
}

func writeFile(t *testing.T, path, text string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
}

// schProject writes ws/proj/top.kicad_sch with one sub-sheet at sheetFile
// (relative to proj) and returns the root path; ws/shared/sub.kicad_sch
// exists for the "../shared/sub.kicad_sch" case.
func schProject(t *testing.T, ws, sheetFile string) string {
	t.Helper()
	root := filepath.Join(ws, "proj", "top.kicad_sch")
	writeFile(t, root, `(kicad_sch (version 20231120) (generator "test") (uuid "11111111-1111-1111-1111-111111111111")
	(sheet (at 10 10) (size 20 20) (uuid "22222222-2222-2222-2222-222222222222")
		(property "Sheetname" "sub" (at 10 9 0))
		(property "Sheetfile" "`+sheetFile+`" (at 10 31 0)))
)
`)
	writeFile(t, filepath.Join(ws, "shared", "sub.kicad_sch"), `(kicad_sch (version 20231120) (generator "test") (uuid "33333333-3333-3333-3333-333333333333"))
`)
	return root
}

func renderCode(err error) string {
	var re *RenderError
	if errors.As(err, &re) {
		return re.Code
	}
	return fmt.Sprint(err)
}

// A sheet and a library outside the project directory travel with the copy
// at their relative place; every page comes out; the temp copy's path reads
// as the user's directory; visible "-0" text survives; two renders are
// byte-identical although the fake stamps a new time each run.
func TestRenderFakeOutsideDependencies(t *testing.T) {
	fakeRenderCLIEnv(t, "")
	ws := t.TempDir()
	root := schProject(t, ws, "../shared/sub.kicad_sch")
	writeFile(t, filepath.Join(ws, "libs", "parts.kicad_sym"), "(kicad_symbol_lib)\n")
	writeFile(t, filepath.Join(ws, "proj", "sym-lib-table"), `(sym_lib_table (version 7)
  (lib (name "parts")(type "KiCad")(uri "${KIPRJMOD}/../libs/parts.kicad_sym")(options "")(descr ""))
  (lib (name "stock")(type "KiCad")(uri "${KICAD10_SYMBOL_DIR}/Device.kicad_sym")(options "")(descr ""))
)
`)
	a, b := filepath.Join(ws, "out-a"), filepath.Join(ws, "out-b")
	m, err := Render(RenderOptions{Sch: root, OutDir: a})
	if err != nil {
		t.Fatal(err)
	}
	if len(m.Files) != 2 || m.Files[0].File != "top-sub.svg" || m.Files[1].File != "top.svg" || m.Files[0].Page != "sub" {
		t.Fatalf("files %+v", m.Files)
	}
	if _, err := Render(RenderOptions{Sch: root, OutDir: b}); err != nil {
		t.Fatal(err)
	}
	for _, f := range m.Files {
		x, _ := os.ReadFile(filepath.Join(a, f.File))
		y, _ := os.ReadFile(filepath.Join(b, f.File))
		if string(x) != string(y) {
			t.Fatalf("%s differs between renders:\n%s\n---\n%s", f.File, x, y)
		}
		s := string(x)
		if strings.Contains(s, os.TempDir()+string(os.PathSeparator)+"pcbpilot-render-") || strings.Contains(s, " date ") {
			t.Errorf("%s keeps the temp copy or the plot date:\n%s", f.File, s)
		}
		for _, keep := range []string{"Path: " + filepath.Join(ws, "proj"), ">-0</text>", ">V=-0.0</text>", `d="M0.0000 1.0000 L2 -0.5"`} {
			if !strings.Contains(s, keep) {
				t.Errorf("%s lost %q:\n%s", f.File, keep, s)
			}
		}
	}
	if r := CompareRenders(a, b); r.Verdict != gate.Pass {
		t.Fatalf("compare %s %+v", r.Verdict, r.Files)
	}
}

// Unresolvable dependencies refuse the render and name what is missing.
func TestRenderFakeUnresolvedDependencies(t *testing.T) {
	fakeRenderCLIEnv(t, "")
	for _, c := range []struct {
		name, sheet, table, want string
	}{
		{"absolute sheet", "ABS", "", "absolute sheet path"},
		{"missing sheet", "../nowhere/sub.kicad_sch", "", "not found"},
		{"outside library missing", "../shared/sub.kicad_sch", `(lib (name "gone")(type "KiCad")(uri "${KIPRJMOD}/../libs/gone.kicad_sym")(options "")(descr ""))`, "gone.kicad_sym"},
		{"undefined variable", "../shared/sub.kicad_sch", `(lib (name "v")(type "KiCad")(uri "${PCBPILOT_TEST_UNDEFINED_DIR}/v.kicad_sym")(options "")(descr ""))`, "PCBPILOT_TEST_UNDEFINED_DIR"},
	} {
		t.Run(c.name, func(t *testing.T) {
			ws := t.TempDir()
			sheet := c.sheet
			if sheet == "ABS" {
				sheet = filepath.ToSlash(filepath.Join(ws, "shared", "sub.kicad_sch"))
			}
			root := schProject(t, ws, sheet)
			if c.table != "" {
				writeFile(t, filepath.Join(ws, "proj", "sym-lib-table"), "(sym_lib_table (version 7)\n  "+c.table+"\n)\n")
			}
			_, err := Render(RenderOptions{Sch: root, OutDir: filepath.Join(ws, "out")})
			if renderCode(err) != "RENDER_DEPENDENCY_UNRESOLVED" || !strings.Contains(err.Error(), c.want) || RenderVerdict(err) != gate.CannotCheck {
				t.Fatalf("err %v, want RENDER_DEPENDENCY_UNRESOLVED naming %q", err, c.want)
			}
			if _, err := os.Stat(filepath.Join(ws, "out")); !os.IsNotExist(err) {
				t.Error("refused render created --out")
			}
		})
	}
}

// kicad-cli results that are not a complete drawing are cannot-check, and a
// failed re-render leaves the previous render exactly as it was.
func TestRenderFakeFailuresKeepPreviousRender(t *testing.T) {
	fakeRenderCLIEnv(t, "")
	ws := t.TempDir()
	root := schProject(t, ws, "../shared/sub.kicad_sch")
	out := filepath.Join(ws, "out")
	if _, err := Render(RenderOptions{Sch: root, OutDir: out}); err != nil {
		t.Fatal(err)
	}
	snapshot := func() map[string]string {
		m := map[string]string{}
		ents, _ := os.ReadDir(out)
		for _, e := range ents {
			b, _ := os.ReadFile(filepath.Join(out, e.Name()))
			m[e.Name()] = string(b)
		}
		return m
	}
	before := snapshot()
	if len(before) != 3 {
		t.Fatalf("first render: %v", before)
	}
	for _, c := range []struct {
		mode, want string
		o          RenderOptions
	}{
		{"skip-sub", "RENDER_INCOMPLETE", RenderOptions{Sch: root}},
		{"empty", "RENDER_BAD_SVG", RenderOptions{Sch: root}},
		{"diag", "RENDER_KICAD_DIAGNOSTIC", RenderOptions{Sch: root}},
		{"exit", "RENDER_KICAD_FAILED", RenderOptions{Sch: root}},
		{"", "RENDER_BAD_INPUT", RenderOptions{PCB: root, Layers: []string{"F.Cu;rm"}}},
		{"no-cli", "RENDER_KICAD_FAILED", RenderOptions{Sch: root}},
	} {
		t.Setenv("PCBPILOT_FAKE_SVG", c.mode)
		if c.mode == "no-cli" {
			t.Setenv("KICAD_CLI", filepath.Join(ws, "no-such-kicad-cli.exe"))
		}
		c.o.OutDir = out
		_, err := Render(c.o)
		if renderCode(err) != c.want {
			t.Errorf("%s: %v, want %s", c.mode, err, c.want)
		}
		if c.want != "RENDER_BAD_INPUT" && RenderVerdict(err) != gate.CannotCheck {
			t.Errorf("%s: verdict %q, want cannot-check", c.mode, RenderVerdict(err))
		}
		after := snapshot()
		if len(after) != len(before) {
			t.Fatalf("%s: --out now %d files, was %d", c.mode, len(after), len(before))
		}
		for k, v := range before {
			if after[k] != v {
				t.Fatalf("%s: %s changed by a failed render", c.mode, k)
			}
		}
	}
}

// render.json may only name plain .svg / .png files of known kinds; any
// other manifest, foreign file or non-regular entry refuses --out.
func TestRenderOutManifestStrict(t *testing.T) {
	fakeRenderCLIEnv(t, "")
	ws := t.TempDir()
	root := schProject(t, ws, "../shared/sub.kicad_sch")
	cases := []struct {
		name, manifest, extra, want string
	}{
		{"parent path", `{"schemaVersion":1,"kind":"sch","files":[{"file":"../victim.svg","kind":"sch-page","sha256":"","bytes":0}]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"sub path", `{"schemaVersion":1,"kind":"sch","files":[{"file":"d/x.svg","kind":"sch-page","sha256":"","bytes":0}]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"other type", `{"schemaVersion":1,"kind":"sch","files":[{"file":"notes.txt","kind":"sch-page","sha256":"","bytes":0}]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"unknown kind", `{"schemaVersion":1,"kind":"sch","files":[{"file":"a.svg","kind":"other","sha256":"","bytes":0}]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"unknown field", `{"schemaVersion":1,"kind":"sch","delete":["x"],"files":[]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"wrong schema", `{"schemaVersion":7,"kind":"sch","files":[]}`, "", "RENDER_OUT_BAD_MANIFEST"},
		{"foreign file", `{"schemaVersion":1,"kind":"sch","files":[]}`, "mine.svg", "RENDER_OUT_NOT_EMPTY"},
		{"listed directory", `{"schemaVersion":1,"kind":"sch","files":[{"file":"dir.svg","kind":"sch-page","sha256":"","bytes":0}]}`, "dir.svg/", "RENDER_OUT_UNSAFE"},
		{"no manifest", "", "mine.svg", "RENDER_OUT_NOT_EMPTY"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			out := filepath.Join(t.TempDir(), "out")
			_ = os.MkdirAll(out, 0o755)
			if c.manifest != "" {
				writeFile(t, filepath.Join(out, RenderManifestName), c.manifest)
			}
			switch {
			case strings.HasSuffix(c.extra, "/"):
				_ = os.MkdirAll(filepath.Join(out, strings.TrimSuffix(c.extra, "/"), "keep"), 0o755)
			case c.extra != "":
				writeFile(t, filepath.Join(out, c.extra), "<svg/>")
			}
			victim := filepath.Join(filepath.Dir(out), "victim.svg")
			writeFile(t, victim, "keep")
			_, err := Render(RenderOptions{Sch: root, OutDir: out})
			if renderCode(err) != c.want {
				t.Fatalf("err %v, want %s", err, c.want)
			}
			var re *RenderError
			if errors.As(err, &re) && !re.Usage() {
				t.Error("an unusable --out is a request error")
			}
			if b, _ := os.ReadFile(victim); string(b) != "keep" {
				t.Error("file outside --out touched")
			}
		})
	}
}

// makeLink links link → target: a symlink, or on Windows without the
// symlink privilege a directory junction (target must then be a directory).
func makeLink(t *testing.T, target, link string) {
	t.Helper()
	if err := os.Symlink(target, link); err == nil {
		return
	} else if runtime.GOOS != "windows" {
		t.Skipf("cannot create a symlink here: %v", err)
	}
	if st, err := os.Stat(target); err != nil || !st.IsDir() {
		t.Skip("no symlink privilege and a junction needs a directory target")
	}
	if out, err := exec.Command("cmd", "/c", "mklink", "/J", link, target).CombinedOutput(); err != nil {
		t.Skipf("cannot create a junction: %v %s", err, out)
	}
}

// A link inside --out where a listed file should be refuses the render
// instead of deleting or writing through it.
func TestRenderOutRefusesLinks(t *testing.T) {
	fakeRenderCLIEnv(t, "")
	ws := t.TempDir()
	root := schProject(t, ws, "../shared/sub.kicad_sch")
	out := filepath.Join(ws, "out")
	if _, err := Render(RenderOptions{Sch: root, OutDir: out}); err != nil {
		t.Fatal(err)
	}
	outside := filepath.Join(ws, "outside")
	writeFile(t, filepath.Join(outside, "precious.svg"), "precious")
	_ = os.Remove(filepath.Join(out, "top.svg"))
	makeLink(t, outside, filepath.Join(out, "top.svg"))
	if _, err := Render(RenderOptions{Sch: root, OutDir: out}); renderCode(err) != "RENDER_OUT_UNSAFE" {
		t.Fatalf("err %v, want RENDER_OUT_UNSAFE", err)
	}
	if b, _ := os.ReadFile(filepath.Join(outside, "precious.svg")); string(b) != "precious" {
		t.Fatal("render reached through a link")
	}
}
